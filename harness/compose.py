def select_claims(
    verified: VerifiedLedger,
    audience: Audience,
    max_claims: int,
) -> tuple[tuple[VerifiedClaim, ...], int]:
    """Return the verified claims for one audience and how many were cut.

    Manager readers get business rules, risks and the edges of what the file
    can show.  Developer and agent readers get every verified claim.  Position
    order (first cite cell, first cite line, numeric id) keeps prompts stable
    across runs and puts a claim before anything that depends on it.
    """
    items = [item for item in verified.items if item.status == "verified"]
    if audience == "manager":
        items = [item for item in items if item.claim.tag in _MANAGER_TAGS]
    items.sort(key=_claim_position)
    limit = max(0, max_claims)
    kept = tuple(items[:limit])
    return kept, len(items) - len(kept)


def _claim_position(item: VerifiedClaim) -> tuple[int, int, int]:
    """Sort key: where the claim starts, then its numeric id as a tie-break."""
    cites = item.claim.cites
    if not cites:
        return (10**9, 10**9, _numeric_suffix(item.claim.id))
    return (cites[0].cell, cites[0].start, _numeric_suffix(item.claim.id))


def _numeric_suffix(claim_id: str) -> int:
    """Extract the first number in a claim id so F2 sorts before F10."""
    match = re.search(r"\d+", claim_id)
    return int(match.group()) if match is not None else 0


def build_messages(
    audience: Audience,
    claims: Sequence[VerifiedClaim | Claim],
    facts: StaticFacts | None,
) -> list[Message]:
    """Build the system/user messages for one document; no I/O, no mutation."""
    lines = ["CLAIMS (sorted by position in the notebook):"]
    for item in claims:
        claim = item.claim if isinstance(item, VerifiedClaim) else item
        lines.append(f"{claim.id} [{claim.kind}, {claim.tag}] {claim.text}")

    if audience in ("developer", "agent") and facts is not None:
        differing = [constant for constant in facts.constants if constant.values_differ]
        if differing:
            lines.append("")
            lines.append("CONSTANT NOTES (from code analysis; not claims):")
            for constant in differing:
                lines.append(f"{constant.name}: assigned {_binding_values(constant)}")

    lines.append("")
    lines.append("Write the document now.")
    return [
        {"role": "system", "content": _PROMPTS[audience]},
        {"role": "user", "content": "\n".join(lines)},
    ]


def _binding_values(constant: ConstantFact) -> str:
    """Literal values of a constant in binding order, e.g. '0.5, then 5.0'."""
    values = [
        binding.value_repr
        for binding in constant.bindings
        if binding.literal and binding.value_repr is not None
    ]
    return ", then ".join(values)


def _unique_cites(cites: Iterable[Citation]) -> tuple[Citation, ...]:
    """Keep the first occurrence of each citation, preserving order."""
    seen: set[tuple[int, int, int]] = set()
    unique: list[Citation] = []
    for cite in cites:
        key = (cite.cell, cite.start, cite.end)
        if key in seen:
            continue
        seen.add(key)
        unique.append(cite)
    return tuple(unique)


def check_document(
    audience: Audience,
    output: DocOut,
    claims: Sequence[VerifiedClaim],
    result: ParseResult,
    facts: StaticFacts,
    verified: VerifiedLedger,
) -> DocumentCheck:
    """Run every deterministic document check and return the final shape.

    Checks 1-4 apply to each model sentence: ids must resolve to selected
    verified claims, a sentence without valid ids is unsourced, numbers and
    code identifiers must occur in the cited claims, and the manager document
    must not contain code vocabulary.  Check 5 appends developer coverage.
    Check 6 pairs agent risks with checks.  Agent static sections are inserted
    here so the renderer receives one ordered document.
    """
    claim_map = {item.claim.id: item.claim for item in claims}
    sections, issues = _assemble(audience, output, claim_map)

    pairing_issues: tuple[str, ...] = ()
    if audience == "agent":
        pairing_issues = _pairing_issues(sections, claims)
        issues.extend(pairing_issues)

    if audience == "developer":
        covered = {cite.cell for item in claims for cite in item.claim.cites}
        sections = _with_coverage(sections, result, verified, covered)

    if audience == "agent":
        sections = _agent_sections(sections, facts)

    for section in sections:
        for sentence in section.sentences:
            for flag in sentence.flags:
                issue = f"{section.heading}: {flag}"
                if issue not in issues:
                    issues.append(issue)

    return DocumentCheck(
        sections=sections,
        issues=tuple(issues),
        used_ids=_used_ids(sections),
        problems=_problems(sections, pairing_issues),
    )


def _expected_headings(audience: Audience) -> tuple[str, ...]:
    """Return the model-written headings for this audience, in order."""
    if audience == "manager":
        return MANAGER_HEADINGS
    if audience == "developer":
        return DEVELOPER_HEADINGS
    return AGENT_MODEL_HEADINGS


def _assemble(
    audience: Audience,
    output: DocOut,
    claim_map: dict[str, Claim],
) -> tuple[tuple[DocSection, ...], list[str]]:
    """Map the reply onto the fixed headings and check each sentence."""
    expected = _expected_headings(audience)
    canonical = {heading.casefold(): heading for heading in expected}
    found: dict[str, SectionOut] = {}
    issues: list[str] = []

    for section in output.sections:
        key = section.heading.strip().casefold()
        if key not in canonical:
            issues.append(f"unexpected section '{section.heading}' ignored")
        elif key not in found:
            found[key] = section

    sections: list[DocSection] = []
    for heading in expected:
        raw_section = found.get(heading.casefold())
        sentences = (
            tuple(
                _check_sentence(audience, sentence, claim_map)
                for sentence in raw_section.sentences
            )
            if raw_section is not None
            else ()
        )
        sections.append(DocSection(heading, sentences))
    return tuple(sections), issues


def _check_sentence(
    audience: Audience,
    raw: SentenceOut,
    claim_map: dict[str, Claim],
) -> DocSentence:
    """Attach citations and run checks 1-4 on one model sentence."""
    valid_ids: list[str] = []
    unknown_ids: list[str] = []
    for claim_id in raw.ids:
        if claim_id in claim_map:
            valid_ids.append(claim_id)
        elif claim_id not in unknown_ids:
            unknown_ids.append(claim_id)

    flags = [f"unknown id {claim_id}" for claim_id in unknown_ids]
    text = raw.text.strip()
    check_identifiers = audience != "manager"

    if not valid_ids:
        flags.append("no claim ids")
        flags.extend(_grounding_flags(text, "", check_identifiers=check_identifiers))
        if audience == "manager":
            flags.extend(_manager_identifier_flags(text))
        return DocSentence(
            text=text,
            ids=(),
            cites=(),
            source="unsourced",
            flags=tuple(flags),
        )

    cited_claims = [claim_map[claim_id] for claim_id in valid_ids]
    cites = _unique_cites(cite for claim in cited_claims for cite in claim.cites)
    claim_text = "\n".join(claim.text for claim in cited_claims)
    flags.extend(
        _grounding_flags(text, claim_text, check_identifiers=check_identifiers)
    )
    if audience == "manager":
        flags.extend(_manager_identifier_flags(text))
    return DocSentence(
        text=text,
        ids=tuple(valid_ids),
        cites=cites,
        source="claims",
        flags=tuple(flags),
    )


def _grounding_flags(
    text: str,
    claim_text: str,
    *,
    check_identifiers: bool,
) -> list[str]:
    """Flag numbers and code identifiers that the cited claims do not contain."""
    claim_numbers = {
        _to_float(match.group()) for match in _NUMBER_RE.finditer(claim_text)
    }
    items: list[str] = []
    for match in _NUMBER_RE.finditer(text):
        value = _to_float(match.group())
        if _skip_number(value):
            continue
        if value not in claim_numbers and match.group() not in items:
            items.append(match.group())

    if check_identifiers:
        lowered = claim_text.lower()
        for match in _IDENT_RE.finditer(text):
            token = match.group()
            if not _identifier_checked(token):
                continue
            if token.lower() in lowered:
                continue
            if token not in items:
                items.append(token)

    if not items:
        return []
    return [f"not in cited claims: {', '.join(items)}"]


def _manager_identifier_flags(text: str) -> list[str]:
    """Flag code vocabulary that a non-technical manager document must avoid."""
    tokens: list[str] = []
    if "`" in text:
        tokens.append("`")
    tokens.extend(match.group(0).lower() for match in _BANNED_WORDS_RE.finditer(text))
    tokens.extend(match.group(0) for match in _CELL_LINE_RE.finditer(text))
    tokens.extend(
        match.group(0)
        for match in _IDENT_RE.finditer(text)
        if _manager_code_token(match.group(0))
    )

    seen: set[str] = set()
    flags: list[str] = []
    for token in tokens:
        key = token.casefold()
        if key in seen:
            continue
        seen.add(key)
        flags.append(f"code identifier: {token}")
    return flags


def _manager_code_token(token: str) -> bool:
    """True for snake_case, camelCase and dotted code names (parts >= 3 chars)."""
    if "_" in token:
        return True
    parts = token.split(".")
    if len(parts) >= 2 and all(len(part) >= 3 for part in parts):
        return True
    return _LOWER_UPPER_RE.search(token) is not None


def _identifier_checked(token: str) -> bool:
    """Match verification's notion of a likely code identifier."""
    if "_" in token:
        return True
    if "." in token and max(len(part) for part in token.split(".")) >= 3:
        return True
    if _LOWER_UPPER_RE.search(token):
        return True
    return any(char.isdigit() for char in token) and any(
        char.isalpha() for char in token
    )


def _to_float(raw: str) -> float:
    """Parse a matched number, accepting thousands separators."""
    return float(raw.replace(",", ""))


def _skip_number(value: float) -> bool:
    """Small counts are too common to be useful grounding evidence."""
    return value.is_integer() and value in (0.0, 1.0, 2.0)


def _pairing_issues(
    sections: Sequence[DocSection],
    claims: Sequence[VerifiedClaim],
) -> tuple[str, ...]:
    """Every risk cited in Risky areas needs a check citing the same claim."""
    by_heading = {section.heading: section for section in sections}
    risky = by_heading["Risky areas"]
    checked: set[str] = set()
    for heading in ("Pre-change checks", "Post-change checks"):
        for sentence in by_heading[heading].sentences:
            checked.update(sentence.ids)

    issues: list[str] = []
    for item in claims:
        if item.claim.tag != "risk":
            continue
        claim_id = item.claim.id
        cited = any(claim_id in sentence.ids for sentence in risky.sentences)
        if cited and claim_id not in checked:
            issues.append(f"risk {claim_id} has no matching check")
    return tuple(issues)


def _with_coverage(
    sections: Sequence[DocSection],
    result: ParseResult,
    verified: VerifiedLedger,
    covered: set[int],
) -> tuple[DocSection, ...]:
    """Append the developer "Not covered" section when cells lack a claim.

    The selected claims are what the developer document could have used; a
    cell is therefore "covered" when a selected claim cites it.  In the normal
    case the sentences cite every selected claim, so this is the same set as
    the sentences' cites.
    """
    uncovered = sorted(
        cell.number
        for cell in result.cells
        if cell.kind in _DOCUMENTABLE and cell.number not in covered
    )
    if not uncovered:
        return tuple(sections)

    sentences = [
        DocSentence(
            text=f"No verified claim covers cells: {_join_cells(uncovered)}.",
            ids=(),
            cites=(),
            source="static",
            flags=(),
        )
    ]
    failed = sorted(
        {cell for region in verified.failed_regions for cell in region.cells}
    )
    if failed:
        sentences.append(
            DocSentence(
                text=f"Extraction failed for cells: {_join_cells(failed)}.",
                ids=(),
                cites=(),
                source="static",
                flags=(),
            )
        )
    return (*sections, DocSection("Not covered", tuple(sentences)))


def _join_cells(cells: Sequence[int]) -> str:
    """Format a sorted cell list as '1, 2, 3'."""
    return ", ".join(str(cell) for cell in cells)


def _agent_sections(
    model_sections: Sequence[DocSection],
    facts: StaticFacts,
) -> tuple[DocSection, ...]:
    """Insert the program-rendered sections and append the limitations."""
    static = _static_sections(facts)
    by_heading = {section.heading: section for section in model_sections}
    ordered: list[DocSection] = []
    for heading in AGENT_FINAL_ORDER:
        section = by_heading.get(heading)
        ordered.append(section if section is not None else static[heading])
    ordered.append(_limits_section(facts))
    return tuple(ordered)


def _limits_section(facts: StaticFacts) -> DocSection:
    """Render the limitations verbatim; the harness never rewrites them."""
    return DocSection(
        LIMITS_HEADING,
        tuple(DocSentence(text, (), (), "static", ()) for text in facts.limitations),
    )


def _static_sections(facts: StaticFacts) -> dict[str, DocSection]:
    """Build the four sections that must not depend on the writing model."""
    return {
        "Mutable state (globals and tables)": _mutable_section(facts),
        "Constants and where they can change": _constants_section(facts),
        "Unused definitions": _unused_section(facts),
        "Invisible dependencies": _invisible_section(facts),
    }


def _mutable_section(facts: StaticFacts) -> DocSection:
    """One sentence per mutated global, then one per table write."""
    by_name: dict[str, list[Mutation]] = {}
    for mutation in facts.mutations:
        by_name.setdefault(mutation.name, []).append(mutation)

    sentences: list[DocSentence] = []
    for name, mutations in by_name.items():
        functions = sorted({mutation.function for mutation in mutations})
        cites = _unique_cites(mutation.cite for mutation in mutations)
        sentences.append(
            DocSentence(
                text=(
                    f"The global {name} is modified in place inside these "
                    f"functions: {', '.join(functions)}."
                ),
                ids=(),
                cites=cites,
                source="static",
                flags=(),
            )
        )

    for table in facts.tables:
        if table.direction != "write":
            continue
        target = table.target
        if target is None:
            target = table.target_expr or "an unresolved target"
        mode = table.mode if table.mode is not None else "not set"
        sentences.append(
            DocSentence(
                text=f"Writes table {target} with mode {mode}.",
                ids=(),
                cites=(table.cite,),
                source="static",
                flags=(),
            )
        )
    return DocSection("Mutable state (globals and tables)", tuple(sentences))


def _constants_section(facts: StaticFacts) -> DocSection:
    """Reassigned values and constants that nothing reads."""
    sentences: list[DocSentence] = []
    for constant in facts.constants:
        literals = [
            binding
            for binding in constant.bindings
            if binding.literal and binding.value_repr is not None
        ]
        if constant.values_differ:
            values = [
                binding.value_repr
                for binding in literals
                if binding.value_repr is not None
            ]
            sentences.append(
                DocSentence(
                    text=(
                        f"{constant.name} is assigned more than once with "
                        f"different values: {', then '.join(values)}."
                    ),
                    ids=(),
                    cites=_unique_cites(binding.cite for binding in literals),
                    source="static",
                    flags=(),
                )
            )
        if constant.never_read:
            first = constant.bindings[0] if constant.bindings else None
            value = (
                first.value_repr
                if first is not None and first.value_repr is not None
                else "?"
            )
            sentences.append(
                DocSentence(
                    text=(
                        f"{constant.name} is assigned {value} and never read "
                        "anywhere in the notebook."
                    ),
                    ids=(),
                    cites=(first.cite,) if first is not None else (),
                    source="static",
                    flags=(),
                )
            )
    return DocSection("Constants and where they can change", tuple(sentences))


def _unused_section(facts: StaticFacts) -> DocSection:
    """One sentence per function that no code in the file references."""
    function_by_name = {function.name: function for function in facts.functions}
    sentences: list[DocSentence] = []
    for name in facts.unused_functions:
        function = function_by_name.get(name)
        if function is None:
            continue
        sentences.append(
            DocSentence(
                text=f"{name} is defined and never referenced.",
                ids=(),
                cites=(function.cite,),
                source="static",
                flags=(),
            )
        )
    return DocSection("Unused definitions", tuple(sentences))


def _invisible_section(facts: StaticFacts) -> DocSection:
    """One sentence per call that the file cannot resolve to a definition."""
    sentences: list[DocSentence] = []
    for call in facts.unresolved_calls:
        text = f"{call.name} is called but not defined in this notebook."
        if call.run_targets:
            text += f" It may come from a %run of {', '.join(call.run_targets)}."
        sentences.append(
            DocSentence(
                text=text,
                ids=(),
                cites=tuple(call.sites[:3]),
                source="static",
                flags=(),
            )
        )
    return DocSection("Invisible dependencies", tuple(sentences))


def _used_ids(sections: Sequence[DocSection]) -> tuple[str, ...]:
    """Distinct claim ids in order of first appearance across the document."""
    seen: set[str] = set()
    used: list[str] = []
    for section in sections:
        for sentence in section.sentences:
            for claim_id in sentence.ids:
                if claim_id in seen:
                    continue
                seen.add(claim_id)
                used.append(claim_id)
    return tuple(used)


def _problems(
    sections: Sequence[DocSection],
    pairing_issues: Sequence[str],
) -> tuple[str, ...]:
    """Build at most ten actionable problems for the one repair attempt."""
    problems = [f"Risky areas: {issue}" for issue in pairing_issues]
    for section in sections:
        for sentence in section.sentences:
            if not sentence.flags:
                continue
            snippet = sentence.text[:60]
            if len(sentence.text) > 60:
                snippet += "..."
            problems.append(
                f'{section.heading}: "{snippet}" -> {"; ".join(sentence.flags)}'
            )
    return tuple(problems[:10])


_DOCUMENT_FAILURES = (
    TruncatedOutput,
    StructuredOutputError,
    LLMTransientError,
    LLMResponseError,
)


def compose_document(
    audience: Audience,
    result: ParseResult,
    verified: VerifiedLedger,
    facts: StaticFacts,
    client: DocumentGenerator,
    *,
    max_claims: int = 120,
) -> Document:
    """Compose one document, with at most two model calls.

    A clean reply costs one call.  A reply with a flagged sentence or an unpaired
    agent risk is sent back once with a list of at most ten concrete problems.
    The second reply is final: whatever is still wrong stays flagged and appears
    in ``Document.issues``.  A missing selection or a provider failure costs no
    model call and yields fixed headings with no model sentences.
    """
    selected, omitted = select_claims(verified, audience, max_claims)
    base_issues: list[str] = []
    if omitted:
        base_issues.append(f"{omitted} claims omitted (limit {max_claims})")

    if not selected:
        output = DocOut(title=_DEFAULT_TITLES[audience], sections=[])
        check = check_document(audience, output, selected, result, facts, verified)
        return _document(audience, output.title, check, base_issues, None)

    messages = build_messages(audience, selected, facts)
    try:
        output = client.generate(messages, DocOut)
    except _DOCUMENT_FAILURES as exc:
        return _failed_document(
            audience, exc, selected, result, facts, verified, base_issues
        )

    check = check_document(audience, output, selected, result, facts, verified)
    if check.needs_retry:
        retry_messages: list[Message] = [
            *messages,
            {"role": "assistant", "content": output.model_dump_json()},
            {
                "role": "user",
                "content": (
                    "Fix these problems and return the complete JSON again:\n- "
                    + "\n- ".join(check.problems)
                ),
            },
        ]
        try:
            output = client.generate(retry_messages, DocOut)
        except _DOCUMENT_FAILURES as exc:
            return _failed_document(
                audience, exc, selected, result, facts, verified, base_issues
            )
        check = check_document(audience, output, selected, result, facts, verified)

    return _document(audience, output.title, check, base_issues, None)


def _document(
    audience: Audience,
    title: str,
    check: DocumentCheck,
    base_issues: Sequence[str],
    error: str | None,
) -> Document:
    """Wrap a deterministic check in a Document without changing its content."""
    return Document(
        audience=audience,
        title=title,
        sections=check.sections,
        issues=tuple([*base_issues, *check.issues]),
        error=error,
        used_ids=check.used_ids,
    )


def _failed_document(
    audience: Audience,
    exc: Exception,
    selected: Sequence[VerifiedClaim],
    result: ParseResult,
    facts: StaticFacts,
    verified: VerifiedLedger,
    base_issues: Sequence[str],
) -> Document:
    """Keep the fixed shape and static sections when writing fails."""
    output = DocOut(title=_DEFAULT_TITLES[audience], sections=[])
    check = check_document(audience, output, selected, result, facts, verified)
    return _document(audience, output.title, check, base_issues, _error_text(exc))


def _error_text(exc: Exception) -> str:
    """A short, safe error; truncation says which setting to change."""
    text = str(exc)[:200]
    if isinstance(exc, TruncatedOutput):
        text = f"{text} (increase max_output_tokens in config.toml)"
    return text


def check_consistency(
    docs: Sequence[Document],
    facts: StaticFacts,
) -> tuple[str, ...]:
    """Flag constants whose stated numbers disagree across documents.

    For every constant with a numeric literal binding: any number in a sentence
    that names the constant must be one of the bound values; and when the
    constant changes value, a document that mentions it must mention all values.
    Static agent sentences count and, because they list every value, satisfy the
    second rule for that document.
    """
    issues: list[str] = []
    for constant in facts.constants:
        bound = _numeric_bindings(constant)
        if not bound:
            continue
        values = _unique_values(bound)
        bound_values = {value for value, _ in values}
        pattern = re.compile(rf"\b{re.escape(constant.name)}\b")

        for doc in docs:
            mentioned = False
            collected: list[tuple[float, str]] = []
            for section in doc.sections:
                for sentence in section.sentences:
                    if pattern.search(sentence.text) is None:
                        continue
                    mentioned = True
                    collected.extend(
                        (_to_float(match.group()), match.group())
                        for match in _NUMBER_RE.finditer(sentence.text)
                    )
            if not mentioned:
                continue

            seen: set[float] = set()
            for value, raw in collected:
                if value in bound_values or value in seen:
                    continue
                seen.add(value)
                issues.append(
                    f"{doc.audience}: {constant.name} stated as {raw}, "
                    f"bound values are {_format_values(values)}"
                )

            if not constant.values_differ:
                continue
            present = {value for value, _ in collected}
            found = [(value, raw) for value, raw in values if value in present]
            missing = [(value, raw) for value, raw in values if value not in present]
            if missing:
                found_text = _format_values(found) if found else "no numbers"
                issues.append(
                    f"{doc.audience}: {constant.name} mentions only "
                    f"{found_text}; also bound: {_format_values(missing)}"
                )
    return tuple(issues)


def _numeric_bindings(constant: ConstantFact) -> list[tuple[float, str]]:
    """Return (value, source text) for literal numeric bindings only."""
    numeric: list[tuple[float, str]] = []
    for binding in constant.bindings:
        if not binding.literal or binding.value_repr is None:
            continue
        try:
            value = float(binding.value_repr)
        except ValueError:
            continue
        numeric.append((value, binding.value_repr))
    return numeric


def _unique_values(
    values: Sequence[tuple[float, str]],
) -> list[tuple[float, str]]:
    """Deduplicate by numeric value, keeping the first spelling."""
    seen: set[float] = set()
    unique: list[tuple[float, str]] = []
    for value, raw in values:
        if value in seen:
            continue
        seen.add(value)
        unique.append((value, raw))
    return unique


def _format_values(values: Sequence[tuple[float, str]]) -> str:
    """Format bound values for an issue, e.g. '0.5, 5.0'."""
    return ", ".join(raw for _, raw in values)


def compose_documents(
    result: ParseResult,
    verified: VerifiedLedger,
    facts: StaticFacts,
    client: DocumentGenerator,
    *,
    max_claims: int = 120,
) -> DocumentSet:
    """Compose manager, developer and agent documents over one ledger.

    Order matters for tests and for a stable UI: manager, developer, agent.
    A failure inside one document is recorded there and does not stop the
    others.  Cross-document constant agreement is checked last.
    """
    manager = compose_document(
        "manager", result, verified, facts, client, max_claims=max_claims
    )
    developer = compose_document(
        "developer", result, verified, facts, client, max_claims=max_claims
    )
    agent = compose_document(
        "agent", result, verified, facts, client, max_claims=max_claims
    )
    docs = (manager, developer, agent)

    used: set[str] = set()
    for doc in docs:
        used.update(doc.used_ids)
    summary = {**verified.summary(), "used": len(used)}
    return DocumentSet(
        manager=manager,
        developer=developer,
        agent=agent,
        issues=check_consistency(docs, facts),
        summary=summary,
        notes=verified.notes,
    )


def render_markdown(
    doc: Document,
    verified: VerifiedLedger | None = None,
) -> str:
    """Render one document; citations are chips generated by the harness.

    Flagged sentences stay visible and carry their flags, never silently
    dropped.  An empty section is shown as empty rather than invented.  When a
    ledger is supplied, the footer repeats how many claims were verified and
    how many were flagged or dropped.
    """
    lines: list[str] = [f"# {doc.title}", ""]
    if doc.error is not None:
        lines.extend([f"> Document generation failed: {doc.error}", ""])

    for section in doc.sections:
        lines.extend([f"## {section.heading}", ""])
        if not section.sentences:
            lines.extend(["_No verified claims for this section._", ""])
            continue
        for sentence in section.sentences:
            prefix = ""
            if sentence.flags:
                prefix = f"[flagged: {'; '.join(sentence.flags)}] "
            chips = ""
            if sentence.cites:
                shown = " ".join(format_citation(cite) for cite in sentence.cites[:4])
                if len(sentence.cites) > 4:
                    shown += f" +{len(sentence.cites) - 4} more"
                chips = f" {shown}"
            lines.extend([f"{prefix}{sentence.text}{chips}", ""])

    if doc.issues:
        lines.extend(["## Issues", ""])
        lines.extend(f"- {issue}" for issue in doc.issues)
        lines.append("")

    lines.append("---")
    if verified is not None:
        summary = verified.summary()
        unused = summary["flagged"] + summary["dropped"]
        lines.append(
            f"Built from {summary['verified']} verified claims; "
            f"{unused} claims were flagged or dropped and not used."
        )
    return "\n".join(lines) + "\n"
