class SentenceOut(BaseModel):
    """One model-written sentence and the claim ids it rests on."""

    text: str = Field(min_length=1, max_length=500)
    ids: list[str] = Field(default_factory=list, max_length=8)


class SectionOut(BaseModel):
    """One model-written section; headings are matched case-insensitively."""

    heading: str = Field(min_length=1, max_length=120)
    sentences: list[SentenceOut] = Field(default_factory=list, max_length=25)


class DocOut(BaseModel):
    """The only structured reply a document call may produce."""

    title: str = Field(min_length=1, max_length=120)
    sections: list[SectionOut] = Field(default_factory=list, max_length=12)


@dataclass(frozen=True, slots=True)
class DocSentence:
    """A rendered sentence with provenance and the flags it collected."""

    text: str
    ids: tuple[str, ...]
    cites: tuple[Citation, ...]
    source: Source
    flags: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class DocSection:
    """A fixed heading plus its sentences; an empty section is meaningful."""

    heading: str
    sentences: tuple[DocSentence, ...]


@dataclass(frozen=True, slots=True)
class Document:
    """One audience document, including what could not be generated."""

    audience: Audience
    title: str
    sections: tuple[DocSection, ...]
    issues: tuple[str, ...]
    error: str | None
    used_ids: tuple[str, ...]

    def to_dict(self) -> dict[str, object]:
        """Return a JSON-safe view; the UI must not depend on dataclasses."""
        return {
            "audience": self.audience,
            "title": self.title,
            "sections": [
                {
                    "heading": section.heading,
                    "sentences": [
                        {
                            "text": sentence.text,
                            "ids": list(sentence.ids),
                            "cites": [
                                {
                                    "cell": cite.cell,
                                    "start": cite.start,
                                    "end": cite.end,
                                }
                                for cite in sentence.cites
                            ],
                            "source": sentence.source,
                            "flags": list(sentence.flags),
                        }
                        for sentence in section.sentences
                    ],
                }
                for section in self.sections
            ],
            "issues": list(self.issues),
            "error": self.error,
            "used_ids": list(self.used_ids),
        }


@dataclass(frozen=True, slots=True)
class DocumentSet:
    """The three documents, cross-document issues, and the run summary."""

    manager: Document
    developer: Document
    agent: Document
    issues: tuple[str, ...]
    summary: dict[str, int]
    notes: tuple[str, ...]

    def to_dict(self) -> dict[str, object]:
        """Return a JSON-safe view of the whole set for saving or the UI."""
        return {
            "manager": self.manager.to_dict(),
            "developer": self.developer.to_dict(),
            "agent": self.agent.to_dict(),
            "issues": list(self.issues),
            "summary": dict(self.summary),
            "notes": list(self.notes),
        }


@dataclass(frozen=True, slots=True)
class DocumentCheck:
    """The deterministic verdict on one model reply."""

    sections: tuple[DocSection, ...]
    issues: tuple[str, ...]
    used_ids: tuple[str, ...]
    problems: tuple[str, ...]

    @property
    def needs_retry(self) -> bool:
        """True when a flagged sentence or a pairing problem remains."""
        return bool(self.problems)


