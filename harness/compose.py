COMMON_PROMPT = """You write one document about a Databricks notebook, using ONLY the numbered claims you are given.
Each claim is a short verified statement about the notebook with an id like F12. You never see the code. A program checks your document.

Rules:
- Every sentence you write must list, in "ids", the claims it is based on. A sentence without ids is shown to the reader as unsourced.
- Use only information from the claims. Do not add facts, reasons, numbers or names that are not in them. Copy numbers and names exactly.
- A sentence may combine several claims (list all their ids). Do not repeat the same claim in many sections.
- Claims marked INFERRED are judgements: phrase them with "could", "may" or "can lead to", never as plain fact. Claims marked NOT_VISIBLE depend on code that is not in the file: say that it is not visible; never say what the missing code does.
- Do not put claim ids, cell numbers or line numbers inside "text"; the program adds the citations.
- If a section has no relevant claims, return it with an empty list of sentences.
- Reply with one JSON object: {"title": "...", "sections": [{"heading": "<exact heading>", "sentences": [{"text": "...", "ids": ["F1", "F2"]}]}]}. Use exactly the section headings listed below, in the same order."""

