"""Compose three audited documents from verified claims.

The writing model never sees the notebook and never types a citation.  It sees
numbered claims (F1, F2, ...) and lists the ids each sentence rests on; this
module attaches the citations of those verified claims.  A citation therefore
cannot come from anywhere except a claim that passed verification.

The agent document mixes model-written prose with sections rendered from
``StaticFacts`` (mutated globals, table writes, reassigned constants, unused
definitions, invisible dependencies).  A final deterministic pass checks
grounding, audience vocabulary, developer cell coverage, agent risk/check
pairing and cross-document constant agreement.
"""

